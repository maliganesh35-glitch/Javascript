console.log(null == 0);  // false
console.log(null >= 0);  // true
console.log(null > 0);   // false

/*Golden Rule 🏆
== → Loose equality; type conversion possible hai.
=== → Strict equality; type conversion nahi hota.
!= → Loose inequality.
!== → Strict inequality.
Best practice: Unnecessary confusion se bachne ke liye === aur !== prefer karo.
*/